#!/usr/bin/env python3
"""Angry Dudes sprite builder.

Every sprite is a grid of palette characters ('.' = transparent). People are
hand-drawn rows; vehicles, siege engines and fort pieces are drawn with the
small shape toolkit in spritekit.py and get an automatic dark outline. The
output is plain JSON, so the HTML prototype and a future iPhone app can both
read the same art.

Usage (from the project folder): python3 tools/build_sprites.py
  Writes assets/sprites.json (the master copy), js/sprites.js (loaded by the
  game) and refreshes the sprite data inside art/angry-dudes-ww2.html.
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import spritekit  # noqa: E402
import sprites_ww2  # noqa: E402
import sprites_ww1  # noqa: E402
import sprites_rome  # noqa: E402
import sprites_castle  # noqa: E402
import sprites_revolution  # noqa: E402
import sprites_vikings  # noqa: E402
import sprites_samurai  # noqa: E402
import sprites_napoleon  # noqa: E402
import sprites_extras  # noqa: E402
import sprites_pirates  # noqa: E402
import sprites_space  # noqa: E402


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    spritekit.common()
    for mod in (sprites_ww2, sprites_ww1, sprites_rome, sprites_castle, sprites_revolution,
                sprites_vikings, sprites_samurai, sprites_napoleon, sprites_extras, sprites_pirates, sprites_space):
        mod.build()
    data = {"palette": spritekit.PALETTE, "teams": spritekit.TEAMS, "sprites": spritekit.SPRITES}
    text = spritekit.to_json(data)
    json.loads(text)
    with open(os.path.join(root, "assets", "sprites.json"), "w") as f:
        f.write(text + "\n")
    with open(os.path.join(root, "js", "sprites.js"), "w") as f:
        f.write("// Generated by tools/build_sprites.py. Edit the builder, not this file.\n")
        f.write("window.ANGRY_SPRITES = " + text + ";\n")
    page = os.path.join(root, "art", "angry-dudes-ww2.html")
    html = open(page).read()
    pat = re.compile(r'(<script type="application/json" id="sprite-data">)(.*?)(</script>)', re.S)
    html = pat.sub(lambda m: m.group(1) + "\n" + text + "\n" + m.group(3), html)
    open(page, "w").write(html)
    print(f"{len(spritekit.SPRITES)} sprites")


if __name__ == "__main__":
    main()
